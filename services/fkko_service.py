def search_fkko(query: str, limit: int = 10) -> list[dict]:
    """
    Поиск по справочнику ФККО.
    Ищет по коду и названию (регистронезависимо).
    Возвращает список совпадений.
    """
    query_lower = query.lower().strip()
    results = []
    for item in FKKO_CATALOG:
        if (
            query_lower in item["name"].lower()
            or query_lower in item["code"].lower()
        ):
            results.append(item)
        if len(results) >= limit:
            break
    return results


def get_fkko_by_code(code: str) -> Optional[dict]:
    """Получить запись ФККО по точному коду."""
    for item in FKKO_CATALOG:
        if item["code"] == code:
            return item
    return None


